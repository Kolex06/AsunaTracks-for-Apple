import Foundation

@main
enum ModelContractTests {
    static func main() throws {
        let fixtures = URL(fileURLWithPath: CommandLine.arguments[1])
        func fixture<T: Decodable>(_ name: String, _: T.Type) throws -> T {
            try Coding.decoder.decode(T.self, from: Data(contentsOf: fixtures.appendingPathComponent(name)))
        }
        let page = try fixture("search.json", MediaPage.self)
        precondition(page.items.count == 2)
        let episodePage = try fixture("media-episodes.json", EpisodePage.self)
        precondition(episodePage.items.count == 25 && episodePage.items.first?.episodeNumber == 1)
        precondition(episodePage.items.first?.imageUrl != nil)
        let pictures = try fixture("media-pictures.json", PicturePage.self)
        precondition(!pictures.items.isEmpty && pictures.items.first?.imageUrl != nil)
        let relations = try fixture("media-relations.json", RelationPage.self)
        precondition(relations.items.contains { $0.relation == "Sequel" })
        precondition(relations.items.flatMap(\.entries).contains { $0.route == "/media/anime/71" })
        let cast = try fixture("media-characters.json", CharacterPage.self)
        precondition(!cast.items.isEmpty && cast.items.first?.voiceActors?.isEmpty == false)
        let people = try fixture("community-users.json", PublicUserPage.self)
        precondition(people.items.count == 4 && people.items.first?.username == "sample-user-2")
        let activity = try fixture("community-activity.json", ActivityPage.self)
        precondition(activity.hasNext == true && activity.items.first?.attachment?.url != nil)
        let profile = try fixture("profile-native.json", ProfileResponse.self)
        precondition(profile.user.username == "sample-user-1" && profile.items?.count == 3)
        precondition(profile.follow?.followers != nil)
        precondition(profile.items?.first?.updatedAt != nil, "List widgets must retain actual server update times")
        let publicCharacters = try fixture("characters-public.json", CharacterPage.self)
        precondition(publicCharacters.hasNext == true && publicCharacters.items.count == 4)
        let publicCharacter = try fixture("character-detail-public.json", CharacterResponse.self)
        precondition(publicCharacter.character.nameKanji != nil && publicCharacter.character.media?.isEmpty == false)
        let sao = page.items[0]
        precondition(sao.id == 32 && sao.mediaType == "anime")
        precondition(sao.displayTitle == "Sword Art Online" && sao.total == 25)
        precondition(sao.asunatracksScore?.score10 == 8.6, "AsunaTracks scores must decode independently of MAL scores")
        precondition(page.pagination?.hasNextPage == true)
        let collectionPage = try fixture("collections-native.json", CollectionPage.self)
        precondition(collectionPage.items.count == 2)
        let collectionDetail = try fixture("collection-native-detail.json", CollectionResponse.self).collection
        precondition(collectionDetail.id == 2 && collectionDetail.items?.count == 7)
        precondition(collectionDetail.items?.first?.media.id == 32)
        precondition(!(collectionDetail.items?.first?.note ?? "").isEmpty)
        let schedule = try fixture("schedule-native.json", ScheduleResponse.self)
        precondition(schedule.items.count == 3 && schedule.items.allSatisfy { $0.date != nil })
        precondition(schedule.items.first?.media?.mediaType == "anime")
        precondition(Set(schedule.items.map(\.identity)).count == schedule.items.count)
        let profileUser = try Coding.decoder.decode(UserResponse.self, from: Data(#"{"user":{"id":42,"username":"profile-test","display_name":"Profile Test","avatar_url":"/avatar/test.png","banner_url":"/banner/test.jpg","bio":"My stories","role":"user"}}"#.utf8)).user!
        precondition(profileUser.avatarUrl == "/avatar/test.png" && profileUser.bannerUrl == "/banner/test.jpg")
        precondition(profileUser.bio == "My stories" && profileUser.displayName == "Profile Test")
        let websiteScore = try Coding.decoder.decode(CommunityScore.self, from: Data(#"{"rating":8.7,"count":3}"#.utf8))
        precondition(websiteScore.displayRating == 8.7)
        precondition(sao.asunatracksScore?.displayRating == 8.6)
        let detail = try fixture("detail.json", DetailResponse.self)
        precondition(detail.media.genres?.contains { $0.name == "Romance" } == true)
        precondition(detail.media.listEntry == nil)
        let characterPage = try fixture("characters.json", CharacterPage.self)
        precondition(characterPage.items.first?.id == 3)
        precondition(characterPage.pagination?.hasNextPage == true)
        let characterDetail = try fixture("character-detail.json", CharacterResponse.self).character
        precondition(characterDetail.name.contains("Asuna"))
        precondition(characterDetail.media?.contains { $0.id == 32 && $0.mediaType == "anime" } == true)
        precondition(characterDetail.voiceActors?.first?.person?.name != nil)
        precondition(detail.media.characters?.isEmpty == false)
        let dedicatedNovels = try fixture("novels-direct.json", NovelCatalogPage.self)
        precondition(dedicatedNovels.items.count == 36 && dedicatedNovels.hasNext)
        precondition((dedicatedNovels.total ?? 0) >= dedicatedNovels.items.count)
        precondition(dedicatedNovels.items.allSatisfy { ($0.type ?? "").localizedCaseInsensitiveContains("novel") })
        let novels = try fixture("novel-search.json", NovelCatalogPage.self)
        let novelItems = novels.items.filter { ($0.type ?? "").localizedCaseInsensitiveContains("novel") }
        precondition(novelItems.count == 5 && !novels.hasNext)
        let novelDetail = try fixture("novel-detail.json", DetailResponse.self).media
        precondition(novelDetail.id == 69142 && novelDetail.mediaType == "manga")
        precondition(!(novelDetail.synopsis ?? "").isEmpty)
        let genres = try fixture("genres.json", GenreResponse.self)
        precondition(genres.genres.count > 50)
        let fields = TrackingFields(status: "watching", progress: 3, progressVolumes: 0, rating: nil,
            favorite: true, notes: "Keep this note", repeatCount: 2, startDate: "2026-10-01", finishDate: nil)
        let encoded = try Coding.encoder.encode(fields)
        let payload = try JSONSerialization.jsonObject(with: encoded) as! [String: Any]
        precondition(payload["repeat_count"] as? Int == 2)
        precondition(payload["progress_volumes"] as? Int == 0)
        let entry = ListEntry(media: sao, status: "watching", progress: 3, progressVolumes: 0,
            rating: nil, favorite: true, notes: "Keep this note", repeatCount: 2, startDate: "2026-10-01", finishDate: nil)
        let accountJSON = Data(##"{"user":{"id":7,"username":"theme-test","ui_theme":"blue","ui_accent_color":"#38bdf8","ui_color_intensity":100}}"##.utf8)
        let account = try Coding.decoder.decode(UserResponse.self, from: accountJSON).user!
        let preferences = try Coding.decoder.decode(UserResponse.self, from: Data(#"{"user":{"id":7,"username":"preferences-test","show_nsfw":true,"profile_private":true,"watching_now_private":true,"playback_list_private":false,"activity_progress_window":120,"mal_sync_interval":"random_10_20"}}"#.utf8)).user!
        precondition(preferences.showNsfw == true && preferences.profilePrivate == true)
        precondition(preferences.watchingNowPrivate == true && preferences.playbackListPrivate == false)
        precondition(preferences.activityProgressWindow == 120 && preferences.malSyncInterval == "random_10_20")
        let theme = account.accountTheme
        precondition(theme.name == "blue" && theme.intensity == 100)
        precondition(abs(theme.accentRGB[0] - 56.0 / 255) < 0.00001)
        precondition(AccountTheme(name: "green", hex: "#ff3f8d", intensity: 100).accentRGB == AccountTheme(name: "green", intensity: 100).accentRGB, "Stale preset colors must follow the selected preset, as on the website")
        precondition(AccountTheme.normalized(" #AbC ") == "aabbcc")
        precondition(AccountTheme.normalized("invalid") == nil)
        let custom = AccountTheme(hex: "#123456", intensity: 50)
        precondition(abs(custom.accentRGB[0] - 83.0 / 255) < 0.00001)
        precondition(AccountTheme(intensity: 999).accentRGB == AccountTheme(intensity: 100).accentRGB)
        precondition(AccountTheme(intensity: -10).accentRGB == AccountTheme(intensity: 15).accentRGB)
        let guest = try Coding.decoder.decode(UserResponse.self, from: Data(#"{"user":{"id":8,"username":"legacy"}}"#.utf8))
        precondition(guest.user?.accountTheme == AccountTheme())
        let watchPayload = try Coding.encoder.encode(ListResponse(items: [entry], theme: theme))
        let watchList = try Coding.decoder.decode(ListResponse.self, from: watchPayload)
        precondition(watchList.theme == theme, "Watch must receive the same account color and intensity")
        precondition(watchList.items[0].progress == 3 && watchList.items[0].canAdvance)
        precondition(watchList.items[0].media.asunatracksScore?.score10 == 8.6)
        precondition(LibraryStatus.onHold.rawValue == "paused")
        let completed = ListEntry(media: sao, status: "completed", progress: 25)
        precondition(!completed.canAdvance)
        print("PASS: live catalog/detail/genre contracts, scores, paging, payload preservation, Watch round-trip, status mapping and completed progress")
    }
}
